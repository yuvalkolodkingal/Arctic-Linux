#!/usr/bin/env node
// Export the design system's icons and app tiles for the shell.
//
//   node shell/dev/export-design-assets.cjs <design project>/components/bundle.js
//
// Writes shell/assets/design-data.js (a QML JavaScript library): the 24px line icons
// (SVG bodies drawn with currentColor), the app tile table (name, category, glyph) and the
// category tints. Icon.qml and AppTile.qml colour them with the active theme's tokens.
// The bundle is the design system's framework-free builder file (window.Arctic); it is
// read-only input and not part of this repository.
'use strict';
const fs = require('fs');
const path = require('path');
const vm = require('vm');

const bundle = process.argv[2];
if (!bundle) {
  console.error('usage: export-design-assets.cjs <path to design components/bundle.js>');
  process.exit(2);
}
const ctx = { window: {}, document: {} };
vm.createContext(ctx);
vm.runInContext(fs.readFileSync(bundle, 'utf8'), ctx);
const A = ctx.window.Arctic;

const icons = {};
for (const name of Object.keys(A.ICONS).sort()) icons[name] = A.ICONS[name];
const apps = {};
for (const [id, a] of Object.entries(A.APPS)) apps[id] = { name: a[0], category: a[1], glyph: a[2], summary: a[3] };
// Category tints (token names) from the design's appTile(); terminal tiles carry snow ink.
const tints = { browser: 'infoSoft', editor: 'surfaceSunken', terminal: 'slate900', shell: 'warmSoft',
  files: 'accentSoft', office: 'successSoft', video: 'warningSoft', extras: 'surfaceSunken', system: 'surfaceSunken' };

const out = `.pragma library
// Generated by shell/dev/export-design-assets.cjs from the Arctic design system bundle.
// Do not edit by hand: re-run the exporter instead.

var ICONS = ${JSON.stringify(icons, null, 1)};

var APPS = ${JSON.stringify(apps, null, 1)};

var TINTS = ${JSON.stringify(tints)};
`;
const target = path.join(__dirname, '..', 'assets', 'design-data.js');
fs.writeFileSync(target, out);
console.log('wrote', path.relative(process.cwd(), target), Object.keys(icons).length, 'icons,', Object.keys(apps).length, 'app tiles');
